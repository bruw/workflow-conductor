#!/usr/bin/env bun
// Converts a real workflow transcript directory into a content-free fixture.
//
//   bun scripts/make-fixture.ts <transcriptDir> <name>
//
// <transcriptDir> is ~/.claude/projects/<proj>/<session>/subagents/workflows/wf_<id>.
// Writes fixtures/<name>.journal.jsonl and fixtures/<name>.metas.json, plus fixtures/<name>.ts
// carrying the same two as exports: the plugin test runner only loads code files and
// refuses node:fs, so tests import the .ts mirror.
//
// Kept: type, agentId, label, phase, a shortened key. Every `result` payload becomes
// `true` (or stays `null`), and metas are reduced to { description, workflowPhase }, so
// nothing an agent read or wrote in the source project reaches this repo.
//
// The committed fixtures were made from:
//   review-41   wf_f8a8409b-dd4  (41 agents, all finished)
//   partial-29  wf_35283561-d5a  (29 agents, 3 never reported a result)

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const [dir, name] = process.argv.slice(2)
if (!dir || !name) {
  console.error('usage: bun scripts/make-fixture.ts <transcriptDir> <name>')
  process.exit(1)
}

const shortKey = (key: unknown) => (typeof key === 'string' ? key.slice(0, 11) : undefined)

const lines: string[] = []
let skipped = 0

for (const line of readFileSync(join(dir, 'journal.jsonl'), 'utf8').split('\n')) {
  if (!line.trim()) continue
  let entry: Record<string, unknown>
  try {
    entry = JSON.parse(line)
  } catch {
    skipped++
    continue
  }

  if (entry.type === 'launched') {
    lines.push(JSON.stringify({ type: 'launched' }))
  } else if (entry.type === 'started') {
    const { agentId, label, phase } = entry
    lines.push(JSON.stringify({ type: 'started', key: shortKey(entry.key), agentId, label, phase }))
  } else if (entry.type === 'result') {
    const result = entry.result === null || entry.result === undefined ? null : true
    lines.push(JSON.stringify({ type: 'result', key: shortKey(entry.key), agentId: entry.agentId, result }))
  } else {
    skipped++
  }
}

const metas: Record<string, { description?: string; workflowPhase?: string }> = {}
for (const file of readdirSync(dir).sort()) {
  const match = /^agent-(.+)\.meta\.json$/.exec(file)
  if (!match?.[1]) continue
  const { description, workflowPhase } = JSON.parse(readFileSync(join(dir, file), 'utf8'))
  metas[match[1]] = { description, workflowPhase }
}

const out = join(import.meta.dir, '..', 'fixtures')
mkdirSync(out, { recursive: true })
const journal = lines.join('\n') + '\n'
const metasJson = JSON.stringify(metas, null, 2)
writeFileSync(join(out, `${name}.journal.jsonl`), journal)
writeFileSync(join(out, `${name}.metas.json`), metasJson + '\n')
writeFileSync(
  join(out, `${name}.ts`),
  [
    `// Generated by scripts/make-fixture.ts from ${name}.journal.jsonl and ${name}.metas.json. Do not edit.`,
    '',
    '/** Contents of the fixture journal, one JSON entry per line. */',
    `export const journal = ${JSON.stringify(lines, null, 2)}.join('\\n') + '\\n'`,
    '',
    `export const metas: Record<string, { description?: string; workflowPhase?: string }> = ${metasJson}`,
    '',
  ].join('\n'),
)

console.log(`${name}: ${lines.length} journal lines, ${Object.keys(metas).length} metas, ${skipped} lines skipped`)
